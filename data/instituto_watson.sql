-- =======================================================
-- BASE DE DATOS DEL INSTITUTO JOHN H. WATSON
-- Organizada en 4 grupos:
--   1. POSTULANTES   (alumnos y docentes que quieren entrar)
--   2. ALUMNOS       (estudiantes inscritos y sus apoderados)
--   3. PROFESORES    (docentes contratados)
--   4. AULA VIRTUAL  (asignaturas, horario, material, notas y avisos)
--   + DIRECTIVA Y COMUNICACIÓN (administración, soporte y contacto)
-- Las contraseñas de ejemplo se guardan cifradas con bcrypt.
-- =======================================================
CREATE DATABASE IF NOT EXISTS instituto_watson;
USE instituto_watson;

-- Limpieza previa: primero las tablas que dependen de otras
DROP TABLE IF EXISTS calificaciones;
DROP TABLE IF EXISTS recursos_aula;
DROP TABLE IF EXISTS horarios;
DROP TABLE IF EXISTS asignaturas;
DROP TABLE IF EXISTS anuncios_aula;
DROP TABLE IF EXISTS notas;
DROP TABLE IF EXISTS estudiantes;
DROP TABLE IF EXISTS profesores;
DROP TABLE IF EXISTS postulaciones_alumnos;
DROP TABLE IF EXISTS postulaciones_docentes;
DROP TABLE IF EXISTS administradores;
DROP TABLE IF EXISTS tickets_soporte;
DROP TABLE IF EXISTS mensajes_contacto;
-- Nombres usados en versiones anteriores
DROP TABLE IF EXISTS solicitudes_estudiantes;
DROP TABLE IF EXISTS solicitudes_profesores;


